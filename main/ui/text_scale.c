int text_scale_tile_cap(text_board_t board, const char *widget_type, int w, int h)
{
    if (widget_type == NULL || w <= 0 || h <= 0) return TEXT_TILE_CAP_NONE;
    const tile_cap_row_t *rows = board == TEXT_BOARD_WIDE10 ? k_tile_caps_wide : k_tile_caps_adaptive;
    const size_t count = board == TEXT_BOARD_WIDE10 ? sizeof(k_tile_caps_wide) / sizeof(k_tile_caps_wide[0])
                                                    : sizeof(k_tile_caps_adaptive) / sizeof(k_tile_caps_adaptive[0]);
    for (size_t i = 0; i < count; i++) {
        if (strcmp(rows[i].type, widget_type) != 0) continue;
        int cap = rows[i].base;
        for (int step = 0; step < TEXT_TILE_CAP_NONE; step++) {
            if (w >= rows[i].w[step] && h >= rows[i].h[step]) cap = step + 1;
        }
        return cap;
    }
    return TEXT_TILE_CAP_NONE;
}

static int interpolate(int px, int x0, int y0, int x1, int y1)
{
    /* rounded linear interpolation (also used to extrapolate: the slope of the nearest segment) */
    const int num = (px - x0) * (y1 - y0);
    const int den = x1 - x0;
    const int half = den / 2;
    return y0 + (num >= 0 ? (num + half) / den : -((-num + half) / den));
}

void text_scale_text_metrics(int px, int *line_height, int *base_line)
{
    const int n = (int)(sizeof(k_text_metrics) / sizeof(k_text_metrics[0]));
    int i = 0;
    while (i < n - 2 && px > k_text_metrics[i + 1].px) i++;
    const text_metrics_row_t *a = &k_text_metrics[i];
    const text_metrics_row_t *b = &k_text_metrics[i + 1];
    int lh = interpolate(px, a->px, a->line_height, b->px, b->line_height);
    int bl = interpolate(px, a->px, a->base_line, b->px, b->base_line);
    if (lh < 1) lh = 1;
    if (bl < 0) bl = 0;
    if (line_height != NULL) *line_height = lh;
    if (base_line != NULL) *base_line = bl;
}

