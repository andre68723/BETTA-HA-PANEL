static const uint8_t k_steps[TEXT_STEP_COUNT] = {16, 20, 24, 28, 32, 36, 42, 48, 56, 64};

/* line height / base line of the former lv_font_conv Poppins fonts at the step sizes */
typedef struct { uint8_t px, line_height, base_line; } text_metrics_row_t;
static const text_metrics_row_t k_text_metrics[] = {
    {16, 21, 5}, {20, 25, 6}, {24, 32, 7}, {28, 35, 7}, {32, 39, 8},
    {36, 44, 9}, {42, 53, 11}, {48, 60, 13}, {56, 69, 15}, {64, 80, 18},
};

int text_scale_step_px(int index) { return k_steps[text_scale_clamp_index(index)]; }

int text_scale_clamp_index(int index)
{
    if (index < 0) return 0;
    if (index > TEXT_STEP_COUNT - 1) return TEXT_STEP_COUNT - 1;
    return index;
}

int text_scale_clamp_user_step(int step)
{
    if (step < 0) return 0;
    if (step > TEXT_USER_STEP_MAX) return TEXT_USER_STEP_MAX;
    return step;
}

int text_scale_role_index(ui_text_role_t role)
{
    switch (role) {
    case UI_TEXT_META: return 1;
    case UI_TEXT_LABEL: return 2;
    case UI_TEXT_VALUE: return 3;
    case UI_TEXT_KEY: return 5;
    case UI_TEXT_HERO: return 6;
    default: return -1;
    }
}

/* The 10-inch boards (about 149 ppi) take the Panel4's role sizes (offset 0). A negative offset was tried first, because the pixels are larger and the
 * same physical size needs fewer of them, but it made every former 20 px title and note 16 px on a panel that is read from further away: measured on
 * the paneljc against the bitmap fonts, titles and metadata of almost every tile shrank. The 16 px size stays the floor for fitting. */
int text_scale_board_offset(text_board_t board)
{
    switch (board) {
    case TEXT_BOARD_TAB5: return 1;
    default: return 0;
    }
}

int text_scale_board_min_index(text_board_t board)
{
    return board == TEXT_BOARD_WIDE10 ? 0 : 1; /* 16 px on the 10-inch boards, 20 px on the denser ones */
}

int text_scale_index(text_board_t board, ui_text_role_t role, int user_step)
{
    const int base = text_scale_role_index(role);
    if (base < 0) return -1;
    const int min = text_scale_board_min_index(board);
    int board_index = text_scale_clamp_index(base + text_scale_board_offset(board));
    if (board_index < min) board_index = min;
    int index = text_scale_clamp_index(board_index + text_scale_clamp_user_step(user_step));
    if (index < min) index = min;
    return index;
}

int text_scale_index_capped(text_board_t board, ui_text_role_t role, int user_step, int max_extra)
{
    const int index = text_scale_index(board, role, user_step);
    if (index < 0) return -1;
    /* max_extra may be -1: a tile that must not grow beyond what a board shows at the standard step (the 10-inch boards' offset is -1) */
    const int limit = text_scale_clamp_index(text_scale_role_index(role) + (max_extra < -1 ? -1 : max_extra));
    const int min = text_scale_board_min_index(board);
    int capped = index < limit ? index : limit;
    if (capped < min) capped = min;
    return capped;
}

int text_scale_px_capped(text_board_t board, ui_text_role_t role, int user_step, int max_extra)
{
    const int index = text_scale_index_capped(board, role, user_step, max_extra);
    return index < 0 ? 0 : k_steps[index];
}

int text_scale_px(text_board_t board, ui_text_role_t role, int user_step)
{
    const int index = text_scale_index(board, role, user_step);
    return index < 0 ? 0 : k_steps[index];
}

int text_scale_floor_px(text_board_t board) { return k_steps[text_scale_board_min_index(board)]; }

int text_scale_max_px(void) { return k_steps[TEXT_STEP_COUNT - 1]; }

