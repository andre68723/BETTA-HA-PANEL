"""Extract resolved package versions from an IDF component manager
dependencies.lock file and emit a small C header of #define strings.

Run at CMake configure time (see main/CMakeLists.txt) so the web UI's
/api/version endpoint can report exactly which component versions were
actually resolved for this build, not just what the manifest requested.

dependencies.lock is a flat-ish YAML document; a top-level package block
looks like:

  dependencies:
    espressif/esp_lvgl_port:          # 2-space indent: package name
      component_hash: ...
      dependencies:
      - name: idf
        version: '>=5.2'              # 6-space indent: a dependency's
                                       # version *constraint* - not what
                                       # we want.
      version: 2.9.0                  # 4-space indent: the package's own
                                       # *resolved* version - what we want.

We avoid a PyYAML dependency (not guaranteed present in every IDF python
env) with a small indentation-aware line scan instead of a real parser.
"""
import argparse
import re
import sys

# Registry packages are "namespace/name"; components vendored under components/
# appear without a namespace.
PACKAGE_RE = re.compile(r"^  ([A-Za-z0-9_.\-]+(?:/[A-Za-z0-9_.\-]+)?):\s*$")
VERSION_RE = re.compile(r"^    version:\s*['\"]?([^'\"#]+?)['\"]?\s*$")


def parse_lock(path):
    """Return {"espressif/esp_hosted": "2.11.7", ...} for top-level packages."""
    versions = {}
    current_pkg = None
    with open(path, "r", encoding="utf-8") as f:
        for line in f:
            line = line.rstrip("\n")
            pkg_match = PACKAGE_RE.match(line)
            if pkg_match:
                current_pkg = pkg_match.group(1)
                continue
            if current_pkg is None:
                continue
            ver_match = VERSION_RE.match(line)
            if ver_match:
                versions[current_pkg] = ver_match.group(1).strip()
                current_pkg = None  # only the first (own) version line counts
    return versions


def main():
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--lock", required=True, help="Path to a dependencies.lock file")
    ap.add_argument("--out", required=True, help="Output header path")
    ap.add_argument(
        "--package",
        action="append",
        default=[],
        metavar="PKG=MACRO",
        help="Map a lock package name to a C macro suffix, e.g. "
        "espressif/esp_lvgl_port=ESP_LVGL_PORT. May be repeated.",
    )
    ap.add_argument(
        "--define",
        action="append",
        default=[],
        metavar="NAME=VALUE",
        help="Emit an additional #define NAME \"VALUE\" line verbatim, for "
        "build metadata not sourced from the lock file (e.g. a git commit "
        "SHA). Included in the same file as --package output so the "
        "no-change-needed comparison below accounts for it too. May be "
        "repeated.",
    )
    args = ap.parse_args()

    try:
        versions = parse_lock(args.lock)
    except OSError as exc:
        print(f"generate_component_versions.py: cannot read {args.lock}: {exc}", file=sys.stderr)
        versions = {}

    lines = [
        "/* Auto-generated by tools/generate_component_versions.py - do not edit. */",
        "#pragma once",
        "",
    ]
    for entry in args.package:
        pkg, _, macro = entry.partition("=")
        version = versions.get(pkg, "")
        escaped = version.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'#define APP_COMPONENT_VERSION_{macro} "{escaped}"')
    for entry in args.define:
        name, _, value = entry.partition("=")
        escaped = value.replace("\\", "\\\\").replace('"', '\\"')
        lines.append(f'#define {name} "{escaped}"')

    content = "\n".join(lines) + "\n"

    try:
        with open(args.out, "r", encoding="utf-8") as f:
            if f.read() == content:
                return  # avoid needless rebuilds when nothing changed
    except OSError:
        pass

    with open(args.out, "w", encoding="utf-8") as f:
        f.write(content)


if __name__ == "__main__":
    main()
