def popup_image(key, label):
    """One popup example in the default Glow style (a widget guide shows each extra UI once, not in every style)."""
    path = ROOT / f"docs/img/gallery/{key}_glow.png"
    width, height = struct.unpack(">II", path.read_bytes()[16:24])
    src = f"../img/gallery/{path.name}"
    return (f'<a href="{src}"><img src="{src}" alt="{html.escape(label)}, glow" loading="lazy" '
            f'width="{width}" height="{height}" style="width: {width * 0.8:g}px"></a>')


