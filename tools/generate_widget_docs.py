def size_limits():
    source = (ROOT / "main/layout/widget_types.c").read_text()
    pattern = r'\{"([\w]+)",\s*\{\s*(\d+),\s*(\d+),\s*(\w+),\s*(\w+)\},\s*"([^"]+)"\}'
    return {kind: (int(w), int(h), mw, mh, domains)
            for kind, w, h, mw, mh, domains in re.findall(pattern, source)}


def variant_minimums():
    source = (ROOT / "main/layout/widget_types.c").read_text()
    pattern = r'\{"([\w]+)",\s*"([\w]+)",\s*\{\s*(\d+),\s*(\d+),\s*\w+,\s*\w+\}\}'
    variants = {}
    for kind, variant, width, height in re.findall(pattern, source):
        variants.setdefault(kind, []).append((variant, int(width), int(height)))
    return variants


def preview_figures(rows, image_dir="gallery"):
    """One figure per distinct functional variant; the optional gallery owns style comparisons."""
    figures = []
    for row in rows:
        for key, tile in row["tiles"]:
            path = ROOT / f"docs/img/{image_dir}/{key}_glow.png"
            if not path.is_file():
                continue
            width, height = struct.unpack(">II", path.read_bytes()[16:24])
            label = html.escape(tile["title"])
            src = f"../img/{image_dir}/{path.name}"
            figures.append((f'<a href="{src}"><img src="{src}" alt="{label}, Glow style" loading="lazy" '
                            f'width="{width}" height="{height}" style="width: {width * 0.8:g}px"></a>', label))
    return figures


def figure_block(figures, captions=True):
    """The page title names the main preview, so it goes without a caption; variants keep theirs."""
    items = [f"<figure>{image}\n<figcaption>{label}</figcaption></figure>" if captions else f"<figure>{image}</figure>"
             for image, label in figures]
    return ['<div class="widget-previews">', *items, "</div>", ""]


def check_summary(kind, domains, summary):
    """The summary names every primary domain, so a reader sees at once what the widget can use."""
    if domains == "*":
        return
    missing = [d for d in domains.split("|") if f"`{d}.*`" not in summary]
    if missing:
        raise RuntimeError(f"{kind}: name {', '.join(missing)} in its summary")


def entity_table(entities):
    if not entities:
        return ["None; the spacer has no entity.", ""]
    lines = ["| Entity | Domains |", "| --- | --- |"]
    lines += [f"| {role}{'' if required else ' *(optional)*'} | {domains} |" for role, domains, required in entities]
    return lines + [""]


def options_table(options):
    if not options:
        return ["No options beyond the entities; the controls follow what the entity supports.", ""]
    lines = ["| Option | Effect |", "| --- | --- |"]
    lines += [f"| {label} | {effect.replace('|', '&#124;')} |" for label, effect in options]
    return lines + [""]


def size_lines(kind, limits, variants):
    w, h, mw, mh, _domains = limits[kind]
    minimum = f"- Minimum: **{w} × {h} px**"
    if kind in variants:
        minimum += " by default; " + "; ".join(f"**{vw} × {vh} px** for {variant.replace('_', ' ')}" for variant, vw, vh in variants[kind])
    max_w = "dashboard width" if mw == "CBW" else f"{mw} px"
    max_h = "dashboard height" if mh == "CBH" else f"{mh} px"
    return [minimum + ".", f"- Maximum: **{max_w} × {max_h}**, capped by the display's dashboard area.", "",
            "The minimum is a validation limit, not a recommended size. [Choose your display](../choose-display.md) lists the "
            "dashboard geometry; [Widget anatomy](../widget-anatomy.md) explains spacing and touch targets.", ""]


def main():
    OUT.mkdir(exist_ok=True)
    data = json.loads((ROOT / "tests/simulator/gallery_data.json").read_text())
    grouped = {}
    for row in build_rows(build_spec(data["entities"])):
        grouped.setdefault(row["tiles"][0][1]["type"], []).append(row)
    limits = size_limits()
    variants = variant_minimums()
    expected = set(limits) - {"roborock_tile"}
