def readable_options(text):
    for field, label in FIELD_LABELS.items():
        text = re.sub(rf"\b{field}\b", label, text)
    return text


def size_limits():
    source = (ROOT / "main/layout/widget_types.c").read_text()
    pattern = r'\{"([\w]+)",\s*\{\s*(\d+),\s*(\d+),\s*(\w+),\s*(\w+)\},\s*"([^"]+)"\}'
    return {kind: (int(w), int(h), mw, mh, domains)
            for kind, w, h, mw, mh, domains in re.findall(pattern, source)}


def variant_minimums():
    source = (ROOT / "main/layout/widget_types.c").read_text()
    pattern = r'\{"([\w]+)",\s*"([\w]+)",\s*\{\s*(\d+),\s*(\d+),\s*\w+,\s*\w+\}\}'
    variants = {}
    for kind, variant, width, height in re.findall(pattern, source):
        variants.setdefault(kind, []).append((variant, int(width), int(height)))
    return variants


def previews(rows, image_dir="gallery"):
    """Show distinct functional variants once; the optional gallery owns style comparisons."""
    lines = ['<div class="widget-previews">']
    count = 0
    for row in rows:
        for key, tile in row["tiles"]:
            path = ROOT / f"docs/img/{image_dir}/{key}_glow.png"
            if not path.is_file():
                continue
            width, height = struct.unpack(">II", path.read_bytes()[16:24])
            label = html.escape(tile["title"])
            src = f"../img/{image_dir}/{path.name}"
            lines += [f'<figure><a href="{src}"><img src="{src}" alt="{label}, Glow style" loading="lazy" '
                      f'width="{width}" height="{height}" style="width: {width * 0.8:g}px"></a>',
                      f'<figcaption>{label}</figcaption></figure>']
            count += 1
    if not count:
        return "No public screenshot is included for this widget yet."
    lines += ["</div>", "", "Glow style, LVGL simulator with synthetic data. Click to enlarge. Other styles keep the same functions."]
    return "\n".join(lines)


