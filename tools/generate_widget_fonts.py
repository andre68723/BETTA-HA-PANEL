"""Regenerate the firmware's fonts: four subset TrueType files and their C arrays.

Every font of the firmware is rendered at run time by lv_tiny_ttf (main/ui/text_font.c) from four small subsets, so no
bitmap font is generated per size any more and lv_font_conv is not needed:

  main/ui/fonts/poppins_medium_subset.ttf  Poppins Medium, the Latin range below, kerning kept
  main/ui/fonts/poppins_bold_subset.ttf    Poppins Bold, the same Latin range for notification emphasis
  main/ui/fonts/mdi_subset.ttf             Material Design Icons, the codepoints in mdi_codepoints.txt
  main/ui/fonts/noto_emoji_subset.ttf      Noto Emoji (monochrome outlines), the codepoints in emoji_codepoints.txt

Each subset is written as TrueType and as a const C array (ttf_poppins_data.c, ttf_mdi_data.c, ttf_emoji_data.c). --web also
embeds the Poppins subset as WOFF2 in the editor's stylesheet, so the layout preview measures text like the panel.

  python3 tools/generate_widget_fonts.py --poppins Poppins-Medium.ttf            # text
  python3 tools/generate_widget_fonts.py --bold Poppins-Bold.ttf                  # notification emphasis
  python3 tools/generate_widget_fonts.py --mdi                                    # icons from the committed full MDI TTF
  python3 tools/generate_widget_fonts.py --emoji 'NotoEmoji[wght].ttf'            # emoji (a variable font is set to wght 400)
  python3 tools/generate_widget_fonts.py --emoji-manifest                         # supported-emoji list for notifications
  python3 tools/generate_widget_fonts.py --web                                    # editor preview font from the Poppins subset
  python3 tools/generate_widget_fonts.py --check                                  # subsets, arrays and manifests agree

Needs fontTools (python3 -m pip install fonttools brotli); --check and the arrays need no network. Sources: Poppins Medium
https://raw.githubusercontent.com/google/fonts/main/ofl/poppins/Poppins-Medium.ttf, Noto Emoji
https://raw.githubusercontent.com/google/fonts/main/ofl/notoemoji/NotoEmoji%5Bwght%5D.ttf, MDI materialdesignicons-webfont.ttf
(Pictogrammers). Licenses: POPPINS-OFL.txt, NOTO_EMOJI-OFL.txt, MDI-APACHE-2.0.txt in main/ui/fonts/.
"""

import argparse
import base64
import io
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parents[1]
FONT_DIR = ROOT / "main/ui/fonts"
EDITOR_CSS = ROOT / "components/webui/www/styles.css"
WEB_BEGIN = "/* BEGIN betta-poppins: generated by tools/generate_widget_fonts.py --web, do not edit */"
WEB_END = "/* END betta-poppins */"

# Latin text range of the panel (also the editor preview's range)
POPPINS_RANGE = "0x20-0x7E,0xA0-0xFF,0x2013-0x2014,0x2018-0x2019,0x201C-0x201D,0x2022,0x2026,0x2080-0x2089,0x20AC,0x2212"
MDI_FULL = FONT_DIR / "materialdesignicons-webfont.ttf"

FONTS = {
    "poppins": {"subset": "poppins_medium_subset.ttf", "data": "ttf_poppins_data.c", "symbol": "ttf_poppins",
                "title": "Poppins Medium", "license": "SIL Open Font License 1.1 (POPPINS-OFL.txt)",
                "copyright": "Copyright 2020 The Poppins Project Authors (https://github.com/itfoundry/Poppins)",
                "features": ["kern"]},
    "bold": {"subset": "poppins_bold_subset.ttf", "data": "ttf_poppins_bold_data.c", "symbol": "ttf_poppins_bold",
             "title": "Poppins Bold", "license": "SIL Open Font License 1.1 (POPPINS-OFL.txt)",
             "copyright": "Copyright 2020 The Poppins Project Authors (https://github.com/itfoundry/Poppins)",
             "features": ["kern"]},
    "mdi": {"subset": "mdi_subset.ttf", "data": "ttf_mdi_data.c", "symbol": "ttf_mdi",
            "title": "Material Design Icons", "license": "Apache-2.0 (MDI-APACHE-2.0.txt)",
            "copyright": "Pictogrammers Material Design Icons, https://pictogrammers.com/library/mdi/",
            "features": []},
    "emoji": {"subset": "noto_emoji_subset.ttf", "data": "ttf_emoji_data.c", "symbol": "ttf_emoji",
              "title": "Noto Emoji (monochrome, wght 400)", "license": "SIL Open Font License 1.1 (NOTO_EMOJI-OFL.txt)",
              "copyright": "Copyright 2013-2026 Google LLC, https://github.com/notofonts/noto-emoji",
              "features": []},
}


def parse_range(spec):
    codepoints = set()
    for token in spec.split(","):
        token = token.strip()
        if not token:
            continue
        if "-" in token:
            low, high = token.split("-")
            codepoints.update(range(int(low, 0), int(high, 0) + 1))
        else:
            codepoints.add(int(token, 0))
    return sorted(codepoints)


def read_manifest(path):
    codepoints = []
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        match = re.fullmatch(r"U\+([0-9A-Fa-f]{4,6})", line)
        if not match:
            raise SystemExit(f"{path}: not a U+ codepoint: {line!r}")
        codepoints.append(int(match.group(1), 16))
    if not codepoints:
        raise SystemExit(f"{path}: no codepoints")
    if len(set(codepoints)) != len(codepoints):
        raise SystemExit(f"{path}: duplicate codepoints")
    return codepoints


def codepoints_for(name):
    if name in ("poppins", "bold"):
        return parse_range(POPPINS_RANGE)
    return read_manifest(FONT_DIR / ("mdi_codepoints.txt" if name == "mdi" else "emoji_codepoints.txt"))


def add_poppins_subscripts(font):
    """Poppins has superior 1/2/3 but no subscripts; derive digits from its own outlines."""
    from fontTools.pens.transformPen import TransformPen
    from fontTools.pens.ttGlyphPen import TTGlyphPen

    cmap = font.getBestCmap()
    em = font["head"].unitsPerEm
    glyphs = font.getGlyphSet()
    superior = {1: 0xB9, 2: 0xB2, 3: 0xB3}
    for digit in range(10):
        cp = 0x2080 + digit
        if cp in cmap:
            continue
        native = superior.get(digit)
        source = cmap[native if native in cmap else ord("0") + digit]
        scale = 1 if native in cmap else 0.5
        shift = -0.5 * em if native in cmap else -0.15 * em
        pen = TTGlyphPen(None)
        glyphs[source].draw(TransformPen(pen, (scale, 0, 0, scale, 0, shift)))
        name = f"uni{cp:04X}"
        font.setGlyphOrder(font.getGlyphOrder() + [name])
        font["glyf"][name] = pen.glyph()
        advance, bearing = font["hmtx"][source]
        font["hmtx"][name] = (round(advance * scale), round(bearing * scale))
        for table in font["cmap"].tables:
            if table.isUnicode():
                table.cmap[cp] = name


def subset_font(source, codepoints, features, instance_weight=None, subscripts=False):
    """Subset a font to the codepoints.

    - hinting off: lv_tiny_ttf (stb_truetype) never runs TrueType bytecode; the sources carry no hinting tables but Noto's small gasp.
    - bounds recalculated: stb_truetype sizes a glyph's bitmap from the box in the glyph header, and a webfont exporter can leave that
      box loose (the MDI icons start at x 0 although their ink starts further right). A loose box makes every cached A8 glyph larger
      (about twice the area for the symbol sizes) and differs from the tight boxes of the former bitmap fonts. The scale factor itself
      only depends on unitsPerEm, so the head box does not matter for it. --check verifies that the boxes are tight.
    - no desubroutinize: that only concerns CFF outlines; all four sources are glyf (TrueType) fonts.
    - no layout features but the listed ones, reproducible timestamps."""
    from fontTools import subset
    from fontTools.ttLib import TTFont

    options = subset.Options()
    options.layout_features = list(features)
    options.hinting = False
    options.recalc_bounds = True
    options.notdef_outline = True
    options.recalc_timestamp = False
    options.name_IDs = [0, 1, 2, 3, 4, 5, 6, 13, 14]
    font = TTFont(str(source), recalcBBoxes=True, recalcTimestamp=False)
    if "fvar" in font:
        from fontTools.varLib import instancer
        axes = {axis.axisTag: (instance_weight if axis.axisTag == "wght" and instance_weight else axis.defaultValue)
                for axis in font["fvar"].axes}
        font = instancer.instantiateVariableFont(font, axes, inplace=False)
    if subscripts:
        add_poppins_subscripts(font)
    subsetter = subset.Subsetter(options)
    subsetter.populate(unicodes=codepoints)
    subsetter.subset(font)
    buffer = io.BytesIO()
    font.save(buffer)
    return buffer.getvalue()


def c_array(name, meta, data):
    lines = [f"/* SPDX-License-Identifier: {'OFL-1.1' if 'OFL' in meta['license'] else 'Apache-2.0'}",
             f" * {meta['title']}, a subset made for the panel by tools/generate_widget_fonts.py; generated, do not edit.",
             f" * {meta['copyright']}",
             f" * License: {meta['license']}.",
             " */",
             '#include "ui/fonts/ttf_data.h"', "",
             f"const unsigned char {meta['symbol']}_data[] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ",".join(str(b) for b in data[i:i + 24]) + ",")
    lines += ["};", f"const unsigned int {meta['symbol']}_size = {len(data)};", ""]
    return "\n".join(lines)


def emoji_inc_text():
    codepoints = sorted(read_manifest(FONT_DIR / "emoji_codepoints.txt"))
    lines = ["/* Generated by tools/generate_widget_fonts.py from emoji_codepoints.txt: the emoji the panel can show, sorted. Do not edit. */"]
    for i in range(0, len(codepoints), 8):
        lines.append(" ".join(f"0x{cp:X}U," for cp in codepoints[i:i + 8]))
    return "\n".join(lines) + "\n"


def write_emoji_inc():
    """The supported-emoji list for ui/notification_text.c (a sorted array of codepoints)."""
    (FONT_DIR / "emoji_codepoints.inc").write_text(emoji_inc_text(), encoding="utf-8")
    print(f"emoji_codepoints.inc: {len(read_manifest(FONT_DIR / 'emoji_codepoints.txt'))} codepoints")


def write_font(name, source, instance_weight=None):
    meta = FONTS[name]
    codepoints = codepoints_for(name)
    data = subset_font(source, codepoints, meta["features"], instance_weight, subscripts=name in ("poppins", "bold"))
    (FONT_DIR / meta["subset"]).write_bytes(data)
    (FONT_DIR / meta["data"]).write_text(c_array(name, meta, data), encoding="utf-8")
    print(f"{meta['subset']}: {len(codepoints)} codepoints, {len(data)} bytes; {meta['data']} written")


def write_web_font():
    """The panel's Poppins Medium subset as a WOFF2 data URI in the editor's stylesheet: one fewer request than a separate font
    file, and cached with the fingerprinted CSS."""
    from fontTools.ttLib import TTFont

    font = TTFont(str(FONT_DIR / FONTS["poppins"]["subset"]), recalcTimestamp=False)
    font.flavor = "woff2"
    buffer = io.BytesIO()
    font.save(buffer)
    data = base64.b64encode(buffer.getvalue()).decode("ascii")
    block = (f"{WEB_BEGIN}\n"
             f"/* Poppins Medium, SIL Open Font License 1.1 (main/ui/fonts/POPPINS-OFL.txt); same subset as the panel. */\n"
             f"@font-face {{\n  font-family: \"BETTA Poppins\";\n  font-weight: 500;\n  font-style: normal;\n"
             f"  font-display: block;\n  src: url(data:font/woff2;base64,{data}) format(\"woff2\");\n}}\n{WEB_END}")
    css = EDITOR_CSS.read_text(encoding="utf-8")
    if WEB_BEGIN not in css:
        raise SystemExit(f"{EDITOR_CSS} has no {WEB_BEGIN!r} marker")
    start = css.index(WEB_BEGIN)
    end = css.index(WEB_END, start) + len(WEB_END)
    EDITOR_CSS.write_text(css[:start] + block + css[end:], encoding="utf-8")
    print(f"{EDITOR_CSS}: {len(buffer.getvalue())} bytes WOFF2")


def check():
    """The committed subsets contain exactly the manifest codepoints and the C arrays hold the subset bytes."""
    inc = FONT_DIR / "emoji_codepoints.inc"
    if not inc.is_file() or inc.read_text(encoding="utf-8") != emoji_inc_text():
        print("FAIL emoji_codepoints.inc is missing or does not match emoji_codepoints.txt (run --emoji-manifest)")
        return 1
    try:
        from fontTools.ttLib import TTFont
    except ImportError:
        print("fontTools not installed, skipped (python3 -m pip install fonttools brotli)")
        return 2
    failures = 0
    for name, meta in FONTS.items():
        path = FONT_DIR / meta["subset"]
        if not path.is_file():
            print(f"FAIL {meta['subset']} is missing")
            failures += 1
            continue
        data = path.read_bytes()
        cmap = TTFont(io.BytesIO(data)).getBestCmap()
        want = set(codepoints_for(name))
        have = {cp for cp in cmap if cp >= 0x20 or cp in want}
        missing = sorted(want - have)
        extra = sorted(have - want) if name not in ("poppins", "bold") else []
        if missing or extra:
            print(f"FAIL {meta['subset']}: missing {[hex(c) for c in missing[:8]]} extra {[hex(c) for c in extra[:8]]}")
            failures += 1
        font = TTFont(io.BytesIO(data))
        glyf = font["glyf"]
        loose = 0
        for glyph_name in font.getGlyphOrder():
            glyph = glyf[glyph_name]
            if glyph.numberOfContours <= 0:
                continue
            header = (glyph.xMin, glyph.yMin, glyph.xMax, glyph.yMax)
            glyph.recalcBounds(glyf)
            loose += header != (glyph.xMin, glyph.yMin, glyph.xMax, glyph.yMax)
        if loose:
            print(f"FAIL {meta['subset']}: {loose} glyph(s) have a header box that is not tight (regenerate: bounds are recalculated)")
            failures += 1
        text = (FONT_DIR / meta["data"]).read_text(encoding="utf-8")
        body = re.search(r"_data\[\] = \{(.*?)\};", text, re.S)
        size = re.search(r"_size = (\d+);", text)
        array = bytes(int(x) for x in re.findall(r"\d+", body.group(1))) if body else b""
        if array != data or not size or int(size.group(1)) != len(data):
            print(f"FAIL {meta['data']} does not hold {meta['subset']}")
            failures += 1
    print("font subsets: ok" if not failures else f"font subsets: {failures} problem(s)")
    return 1 if failures else 0


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--poppins", type=Path, help="Poppins-Medium.ttf from Google Fonts")
    parser.add_argument("--bold", type=Path, help="Poppins-Bold.ttf from Google Fonts")
    parser.add_argument("--mdi", nargs="?", const=MDI_FULL, type=Path, help="materialdesignicons-webfont.ttf (default: the committed one)")
    parser.add_argument("--emoji", type=Path, help="NotoEmoji[wght].ttf or a static Noto Emoji Regular")
    parser.add_argument("--emoji-manifest", action="store_true", help="write emoji_codepoints.inc from the manifest (needs no fonts)")
    parser.add_argument("--web", action="store_true", help="write the editor's WOFF2 preview font from the Poppins subset")
    parser.add_argument("--check", action="store_true", help="verify the committed subsets, arrays and manifests")
    args = parser.parse_args()
    if not (args.poppins or args.bold or args.mdi or args.emoji or args.emoji_manifest or args.web or args.check):
        parser.error("pass --poppins, --bold, --mdi, --emoji, --emoji-manifest, --web, --check or a combination")
    for source in (args.poppins, args.bold, args.mdi, args.emoji):
        if source is not None and not source.is_file():
            parser.error(f"font not found: {source}")
    if args.poppins or args.bold or args.mdi or args.emoji or args.web:  # --emoji-manifest and --check of the manifest need no fonts
        try:
            import fontTools  # noqa: F401
        except ImportError:
            raise SystemExit("fontTools is required: python3 -m pip install fonttools brotli")
    if args.poppins:
        write_font("poppins", args.poppins)
    if args.bold:
        write_font("bold", args.bold)
    if args.mdi:
        write_font("mdi", args.mdi)
    if args.emoji:
        write_font("emoji", args.emoji, instance_weight=400)
    if args.emoji or args.emoji_manifest:
        write_emoji_inc()
    if args.web:
        write_web_font()
    if args.check:
        return check()
    return 0


if __name__ == "__main__":
    sys.exit(main())
