"""Render the color emoji of the notification popup into main/ui/fonts/notification_emoji_data.c.

Reads main/ui/fonts/notification_emoji.txt, takes each image from a pinned revision of googlefonts/noto-emoji (2D/png/128, Apache 2.0)
and scales it, premultiplied, to the popup's text sizes. Each image is stored as raw RGB565A8 (an RGB565 plane followed by an A8 plane),
so the panel decodes nothing. Needs Pillow and network access unless the PNGs are cached under --cache.

    python3 tools/generate_notification_emoji.py [--cache DIR] [--check]
"""
import argparse
import io
import re
import sys
import urllib.request
from pathlib import Path

from PIL import Image

NOTO_REVISION = "e20cbc2bbec1926686be9f9bee7d1d2cfa1fea0e"
NOTO_URL = "https://raw.githubusercontent.com/googlefonts/noto-emoji/%s/2D/png/128/emoji_u%04x.png"
SIZES = (20, 24, 28, 32)  # the popup's text px on Panel4, Panel10, PanelJC and Tab5 at user steps 0-2

ROOT = Path(__file__).resolve().parent.parent
FONT_DIR = ROOT / "main/ui/fonts"
MANIFEST = FONT_DIR / "notification_emoji.txt"
SUPPORTED = FONT_DIR / "emoji_codepoints.txt"
OUT = FONT_DIR / "notification_emoji_data.c"


def codepoints(path):
    return [int(m, 16) for m in re.findall(r"^U\+([0-9A-Fa-f]+)", path.read_text(encoding="utf-8"), re.M)]


def fetch(cp, cache):
    name = "emoji_u%04x.png" % cp
    if cache is not None and (cache / name).exists():
        return (cache / name).read_bytes()
    with urllib.request.urlopen(NOTO_URL % (NOTO_REVISION, cp), timeout=30) as response:
        data = response.read()
    if cache is not None:
        cache.mkdir(parents=True, exist_ok=True)
        (cache / name).write_bytes(data)
    return data


def rgb565a8(image, px):
    """Scale premultiplied (no dark fringe), return the RGB565 plane followed by the A8 plane."""
    scaled = image.convert("RGBa").resize((px, px), Image.LANCZOS).convert("RGBA")
    rgb, alpha = bytearray(), bytearray()
    for r, g, b, a in scaled.getdata():
        value = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += value.to_bytes(2, "little")
        alpha.append(a)
    return bytes(rgb + alpha)


def render(cache):
    cps = sorted(set(codepoints(MANIFEST)))
    supported = set(codepoints(SUPPORTED))
    missing = [cp for cp in cps if cp not in supported]
    if missing:
        sys.exit("not in emoji_codepoints.txt (the sanitizer would replace them): " + ", ".join("U+%04X" % cp for cp in missing))
    lines = [
        "/* SPDX-License-Identifier: LicenseRef-FNCL-1.1",
        " * Generated by tools/generate_notification_emoji.py from main/ui/fonts/notification_emoji.txt; do not edit.",
        " * Images: googlefonts/noto-emoji %s, 2D/png/128 (Apache License 2.0), scaled to the popup text sizes, raw RGB565A8." % NOTO_REVISION,
        " */",
        '#include "ui/notification_emoji_data.h"',
        "",
    ]
    for cp in cps:
        image = Image.open(io.BytesIO(fetch(cp, cache))).convert("RGBA")
        for px in SIZES:
            data = rgb565a8(image, px)
            lines.append("static const uint8_t k_u%04x_%d[%d] = {" % (cp, px, len(data)))
            for i in range(0, len(data), 24):
                lines.append("    " + ", ".join("0x%02x" % b for b in data[i:i + 24]) + ",")
            lines.append("};")
    lines += ["", "const notification_emoji_entry_t k_notification_emoji[] = {"]
    for cp in cps:
        cells = ", ".join(
            "{.header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .w = %d, .h = %d, .stride = %d}, "
            ".data_size = %d, .data = k_u%04x_%d}" % (px, px, px * 2, px * px * 3, cp, px) for px in SIZES)
        lines.append("    {0x%04X, {%s}}," % (cp, cells))
    lines += ["};", "", "const unsigned k_notification_emoji_count = %d;" % len(cps), ""]
    return "\n".join(lines)


def check_docs():
    """docs/notifications.md must list every color emoji (and nothing else in its table)."""
    section = (ROOT / "docs/notifications.md").read_text(encoding="utf-8").split("## Emoji", 1)[1].split("\n## ", 1)[0]
    listed = {ord(ch) for ch in section if ord(ch) > 0x2000 and ch not in "\uFE0F\u200d"}
    manifest = set(codepoints(MANIFEST))
    if listed != manifest:
        sys.exit("docs/notifications.md Emoji section differs from notification_emoji.txt: missing %s, extra %s" % (
            ", ".join("U+%04X" % cp for cp in sorted(manifest - listed)) or "-", ", ".join("U+%04X" % cp for cp in sorted(listed - manifest)) or "-"))


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--cache", type=Path, default=None, help="directory for the downloaded Noto PNGs")
    parser.add_argument("--check", action="store_true", help="fail when the committed data differs")
    args = parser.parse_args()
    text = render(args.cache)
    check_docs()
    if args.check:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != text:
            sys.exit("%s is out of date: run tools/generate_notification_emoji.py" % OUT.relative_to(ROOT))
        print("notification emoji: ok")
        return
    OUT.write_text(text, encoding="utf-8")
    print("%s: %d motifs, %d bytes" % (OUT.relative_to(ROOT), len(set(codepoints(MANIFEST))), len(text)))


if __name__ == "__main__":
    main()
