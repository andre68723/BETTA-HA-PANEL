"""Write docs/gallery-<board>.md for Zensical from a device capture set (tools/capture_device_pages.py).

  tools/import_device_captures.py [--board panel4|paneljc] [--from DIR]

Without --from the pages already in docs/img/<board>/ are used. With --from the capture set replaces
docs/img/<board>/ first, so there is always exactly one current set per board (git keeps the history).
"""
import argparse
import json
import shutil
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DOCS = REPO / 'docs'
BOARDS = {
    'panel4': {'label': '4-inch panel', 'title': '4" Waveshare'},
    'paneljc': {'label': '10-inch panel (Guition JC8012P4A1, paneljc)', 'title': '10.1" Guition'},
}
HEADER = '<!-- SPDX-License-Identifier: LicenseRef-FNCL-1.1 | Copyright (c) 2026 andre68723 -- generated by tools/import_device_captures.py -->'


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument('--board', choices=sorted(BOARDS), default='panel4')
    parser.add_argument('--from', dest='source', type=Path, help='capture set that replaces docs/img/<board>/')
    args = parser.parse_args()
    global SET
    SET = DOCS / 'img' / args.board
    if args.source:
        source = args.source.resolve()
        if not (source / 'manifest.json').is_file(): parser.error('--from needs a capture folder with manifest.json')
        if source != SET.resolve():
            shutil.rmtree(SET, ignore_errors=True)
            shutil.copytree(source, SET)
    manifest = json.loads((SET / 'manifest.json').read_text())
    manifest.pop('reference_sha256', None)
    write(manifest, args.board)
    print(f"{len(manifest['pages'])} pages, firmware {manifest.get('firmware')}")


def facts(m):
    w, h = m.get('resolution', [720, 720])
    return [('Captured', m['captured'][:16].replace('T', ' ')), ('Display device', m.get('board', 'panel4')),
            ('Firmware', m.get('firmware', '?')), ('Resolution', f'{w} x {h} pixels'),
            ('Source', m.get('source', 'device framebuffer'))]


def write(m, board):
    pages = m['pages']
    info = BOARDS[board]
    intro = (f"Live screenshots of the pages on the **{info['label']}**, taken from the device framebuffer, not from the "
             "simulator or the editor preview. The images preserve geometry, spacing, clipping and font sizes, but not "
             "the physical brightness or pixel density; judge readability on the panel at its viewing distance. "
             "Values, weather, time and scrolling top-bar text reflect each capture instant. For examples of every "
             "widget in every appearance style see the [widget gallery](gallery.md).")
    md = [HEADER, '', f"# {info['title']}: device captures", '', intro, '', '| Capture | |', '| --- | --- |']
    md += [f'| {k} | {v} |' for k, v in facts(m)]
    md += ['', f'Regenerate with `tools/capture_device_pages.py <panel-ip>` and `tools/import_device_captures.py --board {board} --from <set>`; '
           'see [development](development/testing.md#device-page-captures). The design rules behind the sizes are in '
           '[appearance](appearance.md#panel4-readability-at-30-cm) (written for the 4-inch panel).', '']
    for p in pages:
        md += [f"## {p['title']}", '', f"Page `{p['id']}`.", '', f"![{p['title']}, {board}](img/{board}/{p['image']})", '']
    (DOCS / f'gallery-{board}.md').write_text('\n'.join(md))


if __name__ == '__main__': main()
